const TABLES: Record<Locale, Record<MsgKey, string>> = { en, es, de, it, pt, fr }

function readStored(): Locale | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw && (LOCALES as readonly string[]).includes(raw)) return raw as Locale
  } catch {
    /* ignore */
  }
  return null
}

function browserLocale(): Locale {
  const langs = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const raw of langs) {
    const code = raw.slice(0, 2).toLowerCase()
    if ((LOCALES as readonly string[]).includes(code)) return code as Locale
  }
  return "en"
}

let current: Locale = readStored() ?? browserLocale()

export function getLocale(): Locale {
  return current
}

export function setLocale(next: Locale): void {
  current = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    /* ignore */
  }
  document.documentElement.lang = next === "pt" ? "pt" : next
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const table = TABLES[current] ?? en
  let out = table[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v))
    }
  }
  return out
}

export function localePickerHtml(): string {
  return `
    <label class="locale-picker">
      ${icon("locale", 16)}
      <span class="visually-hidden">${t("locale.label")}</span>
      <select id="ui-lang" class="locale-select" aria-label="${t("locale.label")}">
        ${LOCALE_META.map((m) => `<option value="${m.id}"${m.id === current ? " selected" : ""}>${m.label}</option>`).join("")}
      </select>
    </label>
  `
}

export function toolMsg(id: string, part: "name" | "tag" | "blurb" | "learn1" | "learn2" | "learn3"): string {
  return t(`tool.${id}.${part}` as MsgKey)
}
